    def _create_benchmark(self, benchmark_etree, global_parametersets,
                          global_substitutesets, global_filesets,
                          global_patternsets, version):
        """Create benchmark from etree

        Return a benchmark
        """
        name = \
            Parser._attribute_from_element(benchmark_etree, "name")

        valid_tags = ["parameterset", "substituteset", "fileset", "step",
                      "comment", "patternset", "analyzer", "analyser",
                      "result"]
        for element in benchmark_etree:
            Parser._check_tag(element, valid_tags)

        comment_element = benchmark_etree.find("comment")
        if comment_element is not None:
            comment = comment_element.text
            if comment is None:
                comment = ""
        else:
            comment = ""
        comment = re.sub(r"\s+", " ", comment).strip()
        if self._outpath is None:
            outpath = Parser._attribute_from_element(benchmark_etree,
                                                    "outpath")
            outpath = os.path.expandvars(os.path.expanduser(outpath))
            # Add position of user to outpath
            outpath = os.path.normpath(os.path.join(self.file_path_ref, outpath))
        # Change runtime outpath if specified
        else:
            outpath = self._outpath

        file_path_ref = Parser._get_attr(benchmark_etree, "file_path_ref", ".")

        # Combine global and local sets
        parametersets = \
            Parser._combine_global_and_local_sets(
                global_parametersets,
                self._extract_parametersets(benchmark_etree))

        substitutesets = \
            Parser._combine_global_and_local_sets(
                global_substitutesets,
                self._extract_substitutesets(benchmark_etree))

        filesets = \
            Parser._combine_global_and_local_sets(
                global_filesets, self._extract_filesets(benchmark_etree))

        patternsets = \
            Parser._combine_global_and_local_sets(
                global_patternsets, self._extract_patternsets(benchmark_etree))

        # dict of local steps
        steps = self._extract_steps(benchmark_etree)

        # dict of local analysers
        analyser = self._extract_analysers(benchmark_etree)

        # dict of local results
        results, results_order = self._extract_results(benchmark_etree)

        # File path reference for relative file location
        file_path_ref = \
                os.path.expandvars(os.path.expanduser(file_path_ref))

        # Add position of user to file_path_ref
        file_path_ref = \
            os.path.normpath(os.path.join(self.file_path_ref, file_path_ref))

        benchmark = jube.benchmark.Benchmark(name, outpath,
                                             parametersets, substitutesets,
                                             filesets, patternsets, steps,
                                             analyser, results, results_order,
                                             comment, self._tags, self._tag_docu,
                                             file_path_ref, version)

        return benchmark

    @staticmethod
    def _combine_global_and_local_sets(global_sets, local_sets):
        """Combine global and local sets """
        result_sets = dict(global_sets)
        if set(result_sets) & set(local_sets):
            raise ValueError("\"{0}\" not unique"
                             .format(",".join([name for name in
                                               (set(result_sets) &
                                                set(local_sets))])))
        result_sets.update(local_sets)
        return result_sets

    def _extract_steps_from_database(self, db, benchmark_id):
        """Extract all steps from benchmark database

        Return a dict of steps, e.g. {"compile": Step(...), ...}
        """
        steps = dict()
        # Extract all steps
        steps_attributes = db.select("Step", None, f"benchmark_id='{benchmark_id}'")
        for step_attributes in steps_attributes:
            name, iterations, cycles, depend, export, \
                active, max_async, work_dir, suffix, \
                procs, shared, do_log_file, benchmark_id = step_attributes
            depend = set(val.strip() for val in
                     depend.split(jube.conf.DEFAULT_SEPARATOR) if val.strip())
            export = bool(export)
            active = str(active).lower()
            if do_log_file in ["None", "False", "false"]:
                do_log_file = None
            if do_log_file in ["True", "true"]:
                do_log_file = jube.conf.DO_LOG_FILENAME
            if shared == "":
                raise ValueError("Empty \"shared\" attribute in " +
                                 "<step> found.")
            step = jube.step.Step(name, depend, iterations, work_dir,
                               shared, export, max_async, active, suffix,
                               cycles, procs, do_log_file)
            # Extract related operations
            ops = self._extract_operation_from_database(db, name)
            for op in ops:
                step.add_operation(op)
            uses = self._extract_uses_from_database(db, name)
            if uses:
                step.add_uses(uses)
            steps[step.name] = step
        return steps

    def _extract_operation_from_database(self, db, step_name):
        """Extract all operations from benchmark database

        Return a list of operations
        """
        ops = []
        ops_attributes = db.select("Operation", None, f"step_name='{step_name}'")
        for op_attributes in ops_attributes:
            iid, do, error_fn, async_fn, stdout_fn, \
                stderr_fn, break_fn, active, shared, \
                work_dir, step_name = op_attributes
            active = str(active).lower()
            shared = bool(shared)
            operation = jube.step.Operation(do, async_fn, stdout_fn, stderr_fn,
                                             active, shared, work_dir, break_fn,
                                             error_fn, iid)
            ops.append(operation)
        return ops

